import frappe
from frappe.utils import flt

def get_stock_reconciliation_delta(doc):
    """
    Computes the true quantity delta for a Stock Reconciliation SLE.
    Primary source: Child row (Stock Reconciliation Item).
    Fallback source: Previous SLE qty_after_transaction.
    """
    delta = 0.0
    if doc.voucher_detail_no and frappe.db.exists("Stock Reconciliation Item", doc.voucher_detail_no):
        row_data = frappe.db.get_value(
            "Stock Reconciliation Item",
            doc.voucher_detail_no,
            ["qty", "current_qty"],
            as_dict=True
        )
        if row_data:
            delta = flt(row_data.qty) - flt(row_data.current_qty)
    else:
        prev_sle_qty = frappe.db.sql("""
            select qty_after_transaction from `tabStock Ledger Entry`
            where item_code = %s and warehouse = %s and is_cancelled = 0 and name != %s
              and (posting_datetime < %s or (posting_datetime = %s and creation < %s))
            order by posting_datetime desc, creation desc limit 1
        """, (doc.item_code, doc.warehouse, doc.name, doc.posting_datetime, doc.posting_datetime, doc.creation))
        prev_qty = prev_sle_qty[0][0] if prev_sle_qty else 0.0
        delta = flt(doc.qty_after_transaction) - flt(prev_qty)

    if getattr(doc, "is_cancelled", 0):
        delta = -1.0 * delta

    return delta

def log_stock_ledger_entry(doc, method):
    """
    Hook for Stock Ledger Entry (after_insert).
    Runs on the Cloud Server to log stock changes for branch synchronization.
    """
    # 1. Determine if this SLE is for a Branch Warehouse
    # Assuming Branch Warehouses can be identified by the branch_id in Branch Sync Config.
    # Alternatively, we could map Warehouse -> Branch ID.
    # For now, let's assume we can lookup the Branch ID for this warehouse.
    # (A custom field 'branch_id' on Warehouse would be best).
    # Since we don't have that yet, let's just assume we check all active configs.
    
    # We only log SLEs that are NOT generated by the jk_sync process itself.
    # We can detect this by checking frappe.flags.is_syncing.
    if getattr(frappe.flags, "is_syncing", False):
        return
        
    branch_id = getattr(doc, "branch_id", None)
    if not branch_id:
        # Try to infer from warehouse
        # If the warehouse name contains the branch ID, or we add a custom field.
        # Let's add a custom field lookup
        if frappe.db.has_column("Warehouse", "branch_id"):
            branch_id = frappe.db.get_value("Warehouse", doc.warehouse, "branch_id")
        else:
            branch_id = None
            
    if not branch_id:
        return
        
    # Ignore SLEs from POS Closing (as they are inherently local)
    if doc.voucher_type == "POS Closing Entry":
        return
        
    # Ignore SLEs from POS-generated Sales Invoices (since branches natively deduct their own stock)
    if doc.voucher_type == "Sales Invoice":
        if frappe.db.get_value("Sales Invoice", doc.voucher_no, "is_pos"):
            return
        
    # Determine qty_change
    if doc.voucher_type == "Stock Reconciliation":
        qty_change = get_stock_reconciliation_delta(doc)
        if abs(qty_change) < 0.0001:
            return  # No physical quantity change, skip logging
    else:
        qty_change = doc.actual_qty

    # Log the Delta
    log = frappe.get_doc({
        "doctype": "Cloud Stock Sync Log",
        "branch_id": branch_id,
        "item_code": doc.item_code,
        "warehouse": doc.warehouse,
        "company": doc.company,
        "qty_change": qty_change,
        "reference_doctype": doc.voucher_type,
        "reference_name": doc.voucher_no
    })
    log.insert(ignore_permissions=True)
